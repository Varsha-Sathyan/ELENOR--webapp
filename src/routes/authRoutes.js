const middleware = require('../middleware/authMiddleware');
const router = require('express').Router();
const requireLogin = require('../middleware/requireLogin');
const controller = require('../controllers/authController');
router.use(require('./recoveryRoutes'));
router.get('/auth/session', requireLogin, controller.checkSession);
router.use(['/login', '/signup', '/otp', '/verify-otp', '/resend-otp', '/auth/google'], middleware.redirectAuthenticated);
router.use(require('./googleRoutes'));
router.get('/signup', controller.showSignup);
router.get('/login', controller.showLogin);
router.post('/signup', controller.signup);
router.get(['/verify-otp', '/otp'], controller.showOtp);
router.post(['/verify-otp', '/otp'], controller.verifyOtp);
router.post('/resend-otp', controller.resendOtp);
router.post('/login', controller.login);
module.exports = router;
