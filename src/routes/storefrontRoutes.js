const middleware = require('../middleware/storefrontMiddleware');
const router = require('express').Router();
const requireLogin = require('../middleware/requireLogin');
const controller = require('../controllers/storefrontController');
router.use(['/products', '/cart'], middleware.checkCustomerSession);
router.get('/home', requireLogin, controller.prepareStorefront, controller.showHome);
router.get('/products', controller.prepareStorefront, controller.listProducts);
router.get('/products/:slug', controller.prepareStorefront, controller.showProduct);
router.get('/cart', controller.prepareStorefront, controller.showCart);
router.post('/cart/:slug', controller.updateCart);
module.exports = router;
