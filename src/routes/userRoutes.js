const middleware = require('../middleware/userMiddleware');
const router = require('express').Router();
const requireLogin = require('../middleware/requireLogin');
const controller = require('../controllers/userController');
router.use(['/profile', '/edit-profile', '/logout'], require('../middleware/requireLogin'));
router.use(['/profile', '/edit-profile', '/logout'], middleware.loadAccount);
router.get('/profile', controller.showProfile);
router.get(['/profile/edit', '/edit-profile'], controller.showEditProfile);
router.use(['/profile', '/edit-profile', '/logout'], middleware.verifyCsrf);
router.post('/profile/edit', controller.updateProfile);
router.post('/profile/password', controller.changePassword);
router.use(require('./accountSettingsRoutes'));
router.post('/logout', controller.logout);
module.exports = router;
